/// The seats that offer their selections through a seat's devices. See
/// [`share_selection_devices`].
struct SelectionBorrowers<D: SeatHandler>(RefCell<Vec<WeakSeat<D>>>);

/// Let `seat` offer its clipboard and primary selection through the
/// `wl_data_device` and primary selection devices clients made from `owner`,
/// for a seat without a global, such as one made with
/// [`Seat::add_keyboard_sharing_objects`](crate::input::Seat::add_keyboard_sharing_objects).
///
/// `seat` keeps a selection of its own. A client sees the selection of the
/// seat whose keyboard focuses it: set `seat`'s data device and primary focus
/// as for any seat. A client `seat`'s keyboard focuses sets `seat`'s
/// selection, not `owner`'s. Data control devices, such as clipboard managers,
/// see only `owner`'s selections.
///
/// The compositor must keep the two keyboards from focusing the same client.
pub fn share_selection_devices<D>(seat: &Seat<D>, owner: &Seat<D>)
where
    D: SelectionHandler + 'static,
{
    for each in [seat, owner] {
        each.user_data()
            .insert_if_missing(|| RefCell::new(SeatData::<D::SelectionUserData>::new()));
    }
    let owners = owner
        .user_data()
        .get::<RefCell<SeatData<D::SelectionUserData>>>()
        .unwrap();
    seat.user_data()
        .get::<RefCell<SeatData<D::SelectionUserData>>>()
        .unwrap()
        .borrow_mut()
        .borrow_devices_of(&owners.borrow());
    owner
        .user_data()
        .insert_if_missing(|| SelectionBorrowers::<D>(RefCell::new(Vec::new())));
    let borrowers = owner.user_data().get::<SelectionBorrowers<D>>().unwrap();
    let mut borrowers = borrowers.0.borrow_mut();
    borrowers.retain(|kept| kept.upgrade().is_some());
    borrowers.push(seat.downgrade());
}

/// The seat whose keyboard focuses the client of `device`, made from
/// `owner`: `owner`, or a seat that borrows its devices. `None` if none does,
/// and the client may not set a selection.
pub(crate) fn seat_setting_a_selection<D>(owner: &Seat<D>, device: &ObjectId) -> Option<Seat<D>>
where
    D: SeatHandler + 'static,
    <D as SeatHandler>::KeyboardFocus: crate::wayland::seat::WaylandFocus,
{
    let focuses = |seat: &Seat<D>| {
        seat.get_keyboard()
            .is_some_and(|keyboard| keyboard.client_of_object_has_focus(device))
    };
    if focuses(owner) {
        return Some(owner.clone());
    }
    let borrowers = owner.user_data().get::<SelectionBorrowers<D>>()?;
    let borrowers = borrowers.0.borrow();
    borrowers
        .iter()
        .filter_map(WeakSeat::upgrade)
        .find(|seat| focuses(seat))
}

/// Events that are generated by interactions of the clients with the data device.
pub trait SelectionHandler: Sized + SeatHandler {
    /// UserData attached to server-side selections.
    type SelectionUserData: Clone + Send + Sync + 'static;

    /// A client has set the selection
    #[allow(unused_variables)]
    fn new_selection(&mut self, ty: SelectionTarget, source: Option<SelectionSource>, seat: Seat<Self>) {}

    /// A client requested to read the server-set selection.
    ///
    /// * `mime_type` - the requested mime type
    /// * `fd` - the fd to write into
    #[allow(unused_variables)]
    fn send_selection(
        &mut self,
        ty: SelectionTarget,
        mime_type: String,
        fd: OwnedFd,
        seat: Seat<Self>,
        user_data: &Self::SelectionUserData,
    ) {
    }
}

/// The target for the selection request.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SelectionTarget {
    /// The target for the request is primary selection.
    Primary,
    /// The target for the request is clipboard selection.
    Clipboard,
}

pub(crate) mod private {
    /// `selection_dispatch!(self; Enum(foo) => foo.something())`
    /// expands to the equivalent of
    /// ```ignore
    /// match self {
    ///    Enum::DataDevice(foo) => foo.something(),
    ///    Enum::Primary(foo) => foo.something(),
    ///    Enum::WlrDataControl(foo) => foo.something(),
    ///    Enum::ExtDataControl(foo) => foo.something(),
    /// }
    /// ```
    ///
    /// And `selection_dispatch!(self, other; Enum(foo), EnumNext(zoo) => foo.something(zoo))` expands
    /// to the equivalent of
    /// ```ignore
    /// match (self, other) {
    ///    (Enum::DataDevice(foo), EnumNext::DataDevice(zoo))  => foo.something(zoo),
    ///    (Enum::Primary(foo), EnumNext::Primary(zoo))  => foo.something(zoo),
    ///    (Enum::WlrDataControl(foo), EnumNext::WlrDataControl(zoo))  => foo.something(zoo),
    ///    (Enum::ExtDataControl(foo), EnumNext::ExtDataControl(zoo))  => foo.something(zoo),
    ///    _ => unreachable!(),
    /// }
    /// ```
    ///
    /// The result can be converted to another enum by adding `; as AnotherEnum`
    macro_rules! selection_dispatch {
        ($what:ident; $enum:ident ( $($c1:tt)* ) => $x:expr) => {
            match $what {
                $enum::DataDevice($($c1)*) => $x,
                $enum::Primary($($c1)*) => $x,
                $enum::WlrDataControl($($c1)*) => $x,
                $enum::ExtDataControl($($c1)*) => $x,
            }
        };
        ($what:ident$(, $what_next:ident)+; $enum:ident ( $($c1:tt)*) $(, $enum_next:ident ( $($c2:tt)* ) )+ => $x:expr) => {
            match ($what$(, $what_next)*) {
                ($enum::DataDevice($($c1)*)$(, $enum_next::DataDevice($($c2)*))*) => $x,
                ($enum::Primary($($c1)*)$(, $enum_next::Primary($($c2)*))*) => $x,
                ($enum::WlrDataControl($($c1)*)$(, $enum_next::WlrDataControl($($c2)*))*) => $x,
                ($enum::ExtDataControl($($c1)*)$(, $enum_next::ExtDataControl($($c2)*))*) => $x,
                _ => unreachable!(),
            }
        };
    }

    pub(crate) use selection_dispatch;
}
